import Foundation

// MARK: - AppLanguage

public enum AppLanguage: String, CaseIterable, Sendable {
    case en, ru
}

// MARK: - L10n

public enum L10n {

    public static var language: AppLanguage = .en

    public static func tr(_ key: String) -> String {
        table(language)[key] ?? key
    }

    /// Следующий язык при тумблере в меню (чистая логика, без I/O).
    /// Пункт «0» экрана «Статус» вызывает переключение .en ↔ .ru.
    public static func toggled() -> AppLanguage {
        language == .en ? .ru : .en
    }

    static func table(_ lang: AppLanguage) -> [String: String] {
        switch lang {
        case .en: return en
        case .ru: return ru
        }
    }

