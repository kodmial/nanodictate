#!/usr/bin/env python3
"""Generate WinGet manifests for the NanoDictate Windows installer (#195).

Reads the installer version, download URL, and SHA-256, validates them
fail-closed, and writes the three-file WinGet manifest set for the tentative
package identifier Kodmial.NanoDictate:

  <out>/<version>/Kodmial.NanoDictate.yaml
  <out>/<version>/Kodmial.NanoDictate.installer.yaml
  <out>/<version>/Kodmial.NanoDictate.locale.en-US.yaml

The manifests are validated structurally here but NOT submitted: submission to
microsoft/winget-pkgs needs upstream approval and never counts as installed
evidence. See .github/workflows/winget-submit.yml.

Usage:
  python3 scripts/make_winget_manifests.py --version 0.1.32 \
    --url https://github.com/kodmial/nanodictate/releases/download/v0.1.32/NanoDictate-Setup-0.1.32-x64.exe \
    --sha256 <64-hex> --out windows/package/winget-manifests
"""

import argparse
import re
import sys
from pathlib import Path

PACKAGE_ID = "Kodmial.NanoDictate"
MANIFEST_VERSION = "1.10.0"
VERSION_RE = re.compile(r"^(0\.(0|1)\.(0|[1-9][0-9]*))$")
SHA_RE = re.compile(r"^[0-9a-fA-F]{64}$")


def fail(message):
    print(f"make_winget_manifests: error: {message}", file=sys.stderr)
    sys.exit(1)


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description="Generate WinGet manifests")
    parser.add_argument("--version", required=True, help="X.Y.Z (0.0.x or 0.1.x)")
    parser.add_argument("--url", required=True, help="HTTPS installer URL")
    parser.add_argument("--sha256", required=True, help="64-hex SHA-256 of the installer")
    parser.add_argument("--out", required=True, help="Output directory")
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    version = args.version.strip().lstrip("v").split("-")[0].split("+")[0]
    if not VERSION_RE.match(version):
        fail(f"version '{args.version}' is not an allowed 0.0.x/0.1.x release version")
    url = args.url.strip()
    if not url.startswith("https://github.com/kodmial/nanodictate/releases/download/"):
        fail("url must be the official GitHub Release download for kodmial/nanodictate")
    expected_asset = f"NanoDictate-Setup-{version}-x64.exe"
    if expected_asset not in url:
        fail(f"url must point at {expected_asset}")
    sha = args.sha256.strip().lower()
    if not SHA_RE.match(sha):
        fail("sha256 must be 64 hex characters")
    out_dir = Path(args.out) / version
    out_dir.mkdir(parents=True, exist_ok=True)

    installer_url = url
    version_file = out_dir / f"{PACKAGE_ID}.yaml"
    installer_file = out_dir / f"{PACKAGE_ID}.installer.yaml"
    locale_file = out_dir / f"{PACKAGE_ID}.locale.en-US.yaml"

    version_file.write_text(
        f"""# Generated by scripts/make_winget_manifests.py. Do not hand-edit.
PackageIdentifier: {PACKAGE_ID}
PackageVersion: {version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: {MANIFEST_VERSION}
""",
        encoding="utf-8",
    )
    installer_file.write_text(
        f"""# Generated by scripts/make_winget_manifests.py. Do not hand-edit.
PackageIdentifier: {PACKAGE_ID}
PackageVersion: {version}
InstallerType: inno
Scope: user
Architecture: x64
UpgradeBehavior: uninstallPrevious
Installers:
- Architecture: x64
  InstallerUrl: {installer_url}
  InstallerSha256: {sha.upper()}
  InstallerSwitches:
    Silent: /SILENT
    SilentWithProgress: /SILENT
    Custom: /NORESTART /SUPPRESSMSGBOXES
ManifestType: installer
ManifestVersion: {MANIFEST_VERSION}
""",
        encoding="utf-8",
    )
    locale_file.write_text(
        f"""# Generated by scripts/make_winget_manifests.py. Do not hand-edit.
PackageIdentifier: {PACKAGE_ID}
PackageVersion: {version}
PackageLocale: en-US
Publisher: Kodmial
PackageName: NanoDictate
License: MIT
ShortDescription: Voice dictation on Windows using the shared NanoDictate Rust engine.
Tags:
- dictation
- speech-to-text
- accessibility
ReleaseNotesUrl: https://github.com/kodmial/nanodictate/releases/tag/v{version}
ManifestType: defaultLocale
ManifestVersion: {MANIFEST_VERSION}
""",
        encoding="utf-8",
    )
    print(f"Wrote {version_file}")
    print(f"Wrote {installer_file}")
    print(f"Wrote {locale_file}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
